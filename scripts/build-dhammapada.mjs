#!/usr/bin/env node
/**
 * Build religions/buddhism/dhammapada-data.js from SuttaCentral's bilara-data.
 *
 *   node scripts/build-dhammapada.mjs
 *
 * Sources (both dedicated to the public domain under CC0 1.0):
 *   - Pali: Mahāsaṅgīti Tipiṭaka Buddhavasse 2500, as published by SuttaCentral
 *   - English: Bhikkhu Sujato, "Sayings of the Dhamma" (SuttaCentral publication scpub7)
 *
 * This is a maintenance script. It needs network access, uses only Node
 * built-ins, and is not run by the tests or by CI; its output is committed.
 */
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const REPO = 'suttacentral/bilara-data';
const BRANCH = 'published';
const RAW = `https://raw.githubusercontent.com/${REPO}`;
const OUTPUT = fileURLToPath(new URL('../religions/buddhism/dhammapada-data.js', import.meta.url));
const TOTAL_VERSES = 423;

// One source file per vagga (chapter), named by its verse range.
const VAGGAS = [
  [1, 20], [21, 32], [33, 43], [44, 59], [60, 75], [76, 89], [90, 99], [100, 115], [116, 128],
  [129, 145], [146, 156], [157, 166], [167, 178], [179, 196], [197, 208], [209, 220], [221, 234],
  [235, 255], [256, 272], [273, 289], [290, 305], [306, 319], [320, 333], [334, 359], [360, 382], [383, 423],
];

async function getJSON(url) {
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${response.status} for ${url}`);
  return response.json();
}

/** Segment keys look like "dhp5:3" (verse 5, line 3). ":0" and ":0.x" are headings. */
function linesOf(file, verse) {
  return Object.keys(file)
    .map(key => { const m = key.match(/^dhp(\d+):(\d+)$/); return m && Number(m[1]) === verse && Number(m[2]) >= 1 ? [Number(m[2]), key] : null; })
    .filter(Boolean)
    .sort((a, b) => a[0] - b[0])
    .map(([, key]) => key);
}

async function main() {
  // Pin the exact upstream revision so the committed data can be traced.
  const commit = (await getJSON(`https://api.github.com/repos/${REPO}/commits/${BRANCH}`)).sha;
  const base = `${RAW}/${commit}`;
  const verses = [];

  for (const [first, last] of VAGGAS) {
    const id = `dhp${first}-${last}`;
    const [pali, english] = await Promise.all([
      getJSON(`${base}/root/pli/ms/sutta/kn/dhp/${id}_root-pli-ms.json`),
      getJSON(`${base}/translation/en/sujato/sutta/kn/dhp/${id}_translation-en-sujato.json`),
    ]);

    for (let verse = first; verse <= last; verse++) {
      const paliLines = [];
      const englishLines = [];
      for (const key of linesOf(pali, verse)) {
        const text = pali[key].trim();
        // Each vagga ends with a colophon ("Yamakavaggo paṭhamo."), and the last
        // one with the book's closing summary. Neither is part of the verse.
        if (/vaggo\s+\S+\.$/.test(text)) break;
        paliLines.push(text);
        const translated = (english[key] || '').trim();
        if (translated) englishLines.push(translated);
      }
      if (paliLines.length < 4) throw new Error(`verse ${verse}: only ${paliLines.length} Pali lines`);
      if (englishLines.length === 0) throw new Error(`verse ${verse}: no English text`);
      verses.push({ num: verse, pali: paliLines.join('\n'), english: englishLines.join('\n') });
    }
  }

  if (verses.length !== TOTAL_VERSES) throw new Error(`expected ${TOTAL_VERSES} verses, built ${verses.length}`);
  verses.forEach((v, i) => { if (v.num !== i + 1) throw new Error(`verse numbering breaks at ${v.num}`); });

  const header = `/**
 * Dhammapada, all ${TOTAL_VERSES} verses: Pali text with English translation.
 *
 * GENERATED by scripts/build-dhammapada.mjs. Do not edit by hand.
 *
 * Source: SuttaCentral bilara-data
 *   https://github.com/${REPO}/tree/${commit}
 * Pali:    Mahāsaṅgīti Tipiṭaka Buddhavasse 2500 (root/pli/ms/sutta/kn/dhp)
 * English: Bhikkhu Sujato, "Sayings of the Dhamma" (translation/en/sujato/sutta/kn/dhp)
 * Licence: both are dedicated to the public domain under Creative Commons Zero
 *          (CC0 1.0), https://creativecommons.org/publicdomain/zero/1.0/
 *
 * Lines within a verse are separated by "\\n".
 */
`;
  const body = `window.DHAMMAPADA_VERSES = ${JSON.stringify(verses, null, 1)};\n`;
  await writeFile(OUTPUT, header + body);
  console.log(`Wrote ${verses.length} verses from ${REPO}@${commit.slice(0, 12)} to ${OUTPUT}`);
}

main().catch(error => { console.error(error); process.exit(1); });
